'use strict';
const assert=require('node:assert/strict');
const {execFileSync}=require('node:child_process');
const path=require('node:path');
const {capturedOwnedPoint}=require('../perspective.js');
const data=JSON.parse(execFileSync('python',['-B',path.join(__dirname,'point-fixtures.py')],{encoding:'utf8'}));
const a=capturedOwnedPoint(data.useful,0,0),b=capturedOwnedPoint(data.private,0,0);
assert.equal(data.useful.source.record,103);
assert.deepEqual(a,b,'different private partner state cannot alter displayed own state');
assert.equal(a.own.food,2);assert.equal(a.own.hunger,80);
assert.equal(a.phase,'owned snapshot');assert.equal(a.selected,undefined,'a state capture does not invent a decision');
assert.notDeepEqual(capturedOwnedPoint(data.useful,0,1),capturedOwnedPoint(data.private,0,1),'own private traits may differ when that individual is selected');
const poisoned=structuredClone(data.useful);
poisoned.final_state={observer_events:[{content:'FORGOTTEN_CONTENT',hidden_root:123}]};
poisoned.points[0].state.agents[1].food=999;
poisoned.points[0].state.agents[0].observer_secret='SECRET';
assert.deepEqual(capturedOwnedPoint(poisoned,0,0),a,'observer history and unknown fields cannot supply cognition');
poisoned.points[0].state.agents[0].trust={'1':7};
poisoned.points[0].state.agents[0].memories=[];
const legacy=capturedOwnedPoint(poisoned,0,0);
assert.deepEqual(legacy.own.memories,[]);assert.equal(legacy.own.trust['1'],7,'separately persistent trust survives empty episodes');
legacy.own.trust['1']=999;
assert.equal(poisoned.points[0].state.agents[0].trust['1'],7,'projection is detached');
const later=capturedOwnedPoint(data.useful,1,0);
assert.deepEqual(later.own.memories,data.useful.points[1].state.agents[0].memories,'later state is captured retention, not rebuilt events');
assert.equal(capturedOwnedPoint(data.useful,-1,0),null);
assert.equal(capturedOwnedPoint(data.useful,0,99),null);
assert.equal(capturedOwnedPoint(data.useful,999,0),null);
console.log('Owned-point boundary: real records103/109, private twins, no invented choice, no history recovery, legacy persistence, detached projection and missing-reference rejection passed.');
