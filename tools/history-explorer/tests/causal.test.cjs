const assert=require('node:assert/strict');
const {execFileSync}=require('node:child_process');
const path=require('node:path');
const {resourceRecords,originalValue,orderedChainNodes}=require('../causal.js');
const data=JSON.parse(execFileSync('python',['-B',path.join(__dirname,'causal-fixtures.py')],{maxBuffer:32*1024*1024}));
for(const filter of ['zero','request-leave'])assert.equal(resourceRecords(data['85'],filter,258).length,65);
assert.equal(resourceRecords(data['85'],'transfer',258).length,0);
assert.equal(resourceRecords(data['85'],'request-refuse',258).length,0);
assert.equal(resourceRecords(data['85'],'declined',258).length,65);
assert.equal(resourceRecords(data['85'],'reciprocal',258).length,65);
assert.equal(resourceRecords(data['85'],'unexecuted',258).length,130);
assert(resourceRecords(data['95'],'all',0).length>0);
const ordered=orderedChainNodes(data['107'],data['107'].chains[0],data.timeline107).map(id=>data['107'].nodes[id]);
assert(ordered.findIndex(n=>n.source_kind==='Actual resource execution')>ordered.findLastIndex(n=>n.source_kind==='Arbitration'));
const delivered=Object.values(data['10'].nodes).find(n=>n.source_kind==='Provenance delivery');
assert.equal(originalValue(data.trial,delivered.ref).id,1);
assert.equal(originalValue(data.trial,delivered.ref).listener,0);
assert.throws(()=>originalValue(data.trial,'points[999999]'));
assert.throws(()=>originalValue(data.trial,'__proto__'));
assert.throws(()=>originalValue(data.trial,'points[-1]'));
assert.throws(()=>originalValue(data.trial,'points[0];alert(1)'));
console.log('Actual JS filter:65 completed encounters,130 unexecuted dispositions,correct receipt namespace,large history and invalid reference rejection passed.');
